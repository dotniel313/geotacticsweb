export const publicRecords = () =>
	records.filter((r) => r.archivePublic).sort((a, b) => a.year - b.year || a.title.localeCompare(b.title, 'es'));

export function recordsByFamily(id: FamilyId) {
	return publicRecords().filter((r) => r.primaryFamily === id);
}

export function recordBySlug(slug: string) {
	return records.find((r) => r.slug === slug);
}

export function mappableRecords() {
	return publicRecords().filter((r) => r.coordinates);
}

